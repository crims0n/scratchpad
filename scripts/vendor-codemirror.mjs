import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: ["scripts/codemirror-entry.js"],
  outfile: "src/vendor/codemirror.js",
  bundle: true, format: "esm", platform: "browser", target: "es2022",
  minify: true, metafile: true, legalComments: "none",
  banner: { js: "// CodeMirror 6 — MIT. See codemirror.LICENSE.txt. Generated by npm run vendor:codemirror." }
});
const packages = [...new Set(Object.keys(result.metafile.inputs).map(path =>
  path.match(/^node_modules\/((?:@[^/]+\/)?[^/]+)\//)?.[1]
).filter(Boolean))].sort();
const notices = [];
for (const name of packages) {
  const directory = new URL(`../node_modules/${name}/`, import.meta.url);
  const metadata = JSON.parse(await readFile(new URL("package.json", directory), "utf8"));
  if (metadata.license !== "MIT") throw new Error(`Review the license for ${name}: ${metadata.license}`);
  const license = await readFile(new URL("LICENSE", directory), "utf8");
  notices.push(`${name} ${metadata.version}\n\n${license.trim()}\n`);
}
await writeFile(new URL("../src/vendor/codemirror.LICENSE.txt", import.meta.url), notices.join("\n---\n\n"));
console.log(`Bundled CodeMirror and ${packages.length} MIT-licensed packages for offline use`);
